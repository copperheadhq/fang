def test_at_k5_a_topology_check_names_each_unpermitted_path():
    """AT-K5: the topology half; the ground view is Phase 3."""
    entities = {}
    for connection in (
        conductive("CN-1", "DOM-LOGIC", "NET-MOTOR-STAR"),
        conductive("CN-2", "DOM-MOTOR", "NET-MOTOR-STAR"),
        conductive("CN-3", "DOM-LOGIC", "NET-CHASSIS"),
        conductive("CN-4", "NET-CHASSIS", "DOM-MOTOR"),
    ):
        entities[connection.id] = connection

    constraint = TopologyConstraint(
        authored("TOPO-GND"),
        net="NET-GND",
        mode=TopologyMode.STAR,
        center="NET-MOTOR-STAR",
        branches=("DOM-LOGIC", "DOM-MOTOR"),
    )
    failures = [r for r in constraint.verify(entities) if r.status is CheckStatus.FAIL]
    assert failures
    # Intent is distinct from net equivalence: the same net, a different verdict.
    assert failures[0].paths and "NET-CHASSIS" in failures[0].paths[0]


def test_at_k6_one_safe_edit_round_tripped_to_cad():
    """AT-K6: one edit round-trips with no unrelated electrical change."""
    from fang.elaborate import elaborate
    from fang.kicad import emit_netlist, read_netlist
    from fang.netlist import compile_netlist
    from fang.graph import RemoveEntity

    from examples.divider.divider import Divider

    original = elaborate(Divider, project_id=PROJECT)
    before = compile_netlist(original.snapshot, traits=original.traits)
    text = emit_netlist(before, source="divider.py")

    imported = read_netlist(text, project_id=PROJECT, source="divider.net")
    graph = KernelGraph(Snapshot(PROJECT, "REV-IMPORT", imported.entities))

    target = next(
        e for e in imported.entities.values()
        if isinstance(e, Component) and e.designator == "R2"
    )
    edited = Component(
        target.identity,
        designator=target.designator,
        part="22 kOhm",
        package=target.package,
        provenance=target.provenance,
        source_location=target.source_location,
        extensions=target.extensions,
    )
    proposal = graph.apply(
        Transaction(
            graph.head.hash,
            (
                RemoveEntity(target=target.id, reason="replace"),
                AddEntity(entity=edited, reason="set R2 to 22 kOhm"),
            ),
        )
    )
    assert proposal.accepted

    after = compile_netlist(graph.head)
    changed = {
        c.designator: c.value for c in after.components
    } != {c.designator: c.value for c in before.components}
    assert changed
    # Nothing else moved: every net is untouched by a value change.
    assert [(n.name, [(x.designator, x.pin) for x in n.nodes]) for n in after.nets] == [
        (n.name, [(x.designator, x.pin) for x in n.nodes]) for n in before.nets
    ]
    assert {c.designator for c in after.components} == {
        c.designator for c in before.components
    }


def test_at_k7_external_rule_check_results_are_ingested_after_commit_never_before(kernel):
    """AT-K7."""
    stale = kernel.head.hash
    kernel.apply(Transaction(stale, (AddEntity(entity=Component(authored("CMP-Z"))),)))

    # Ingesting against a snapshot that is not the committed head is refused.
    with pytest.raises(FangError):
        ingest_external_results(
            kernel,
            [CheckResult("drc", CheckStatus.PASS, "CMP-Z", "clearances ok")],
            snapshot_hash=stale,
            record_time=FIXED_TIME,
        )

    proposal = ingest_external_results(
        kernel,
        [CheckResult("drc", CheckStatus.PASS, "CMP-Z", "clearances ok")],
        snapshot_hash=kernel.head.hash,
        record_time=FIXED_TIME,
    )
    assert proposal.accepted
    ingested = [e for e in kernel.head.entities.values() if isinstance(e, Evidence)]
    assert any("drc reported PASS" in e.claim for e in ingested)


def test_at_k8_a_semantic_diff_separates_presentation_from_electrical_change(snapshot):
    """AT-K8: and names the invalidated requirements."""
    before = dict(snapshot.entities)
    after = dict(before)

    # A presentation change.
    identity = before[REGULATOR].identity
    after[REGULATOR] = replace(
        before[REGULATOR], identity=replace(identity, display_name="Main Buck")
    )
    presentation = diff(before, after)
    assert not presentation.electrical

    # An electrical change, with a constraint and a requirement behind it.
    electrical_before = dict(before)
    electrical_before["RULE-1"] = Constraint(
        authored("RULE-1"),
        constraint_kind="max_power_dissipation",
        targets=(REGULATOR,),
        expression=le(Ref(REGULATOR, "power_dissipation", WATTS), Literal.of(Quantity.scalar("1", "W"))),
        source="REQ-PWR-001",
    )
    electrical_after = dict(electrical_before)
    electrical_after[REGULATOR] = electrical_before[REGULATOR].with_parameter(
        "power_dissipation", Value.explicit(Quantity.scalar("0.9", "W"))
    )
    changes = diff(electrical_before, electrical_after)
    assert changes.electrical
    assert "REQ-PWR-001" in changes.invalidated


def test_at_k9_a_rejected_agent_proposal_leaves_state_unchanged_and_still_explains(
    kernel, power_constraint
):
    """AT-K9."""
    from fang.provenance import Actor, ActorKind, ProvenanceOrigin, ProvenanceRecord

    agent_origin = ProvenanceRecord(
        ProvenanceOrigin.GENERATED,
        "agent_proposal",
        Actor(ActorKind.MODEL, "copperhead-agent", "1.0"),
        "REV-000001",
        FIXED_TIME,
    )
    head_before = kernel.head.hash
    entities_before = dict(kernel.head.entities)

    proposal = kernel.propose(
        Transaction(
            kernel.head.hash,
            (
                AddEntity(entity=power_constraint),
                SetParameter(
                    target=REGULATOR,
                    name="power_dissipation",
                    value=Value.explicit(Quantity.scalar("0.5", "W")),
                    reason="agent raised dissipation past the hard limit",
                ),
            ),
            origin=agent_origin,
        )
    )

    assert proposal.rejected
    assert kernel.head.hash == head_before
    assert kernel.head.entities == entities_before
    assert proposal.diagnostics          # it still produces its diagnostics
    assert len(proposal.diff) > 0        # and its diff


def test_at_k10_a_simulation_result_names_its_plan_backend_models_and_gaps():
    """AT-K10."""
    from fang.elaborate import elaborate
    from fang.simulation import (
        Assertion,
        RawResult,
        Transient,
        compile_plan,
        normalize,
    )

    from examples.divider.divider import Divider

    result = elaborate(Divider, project_id=PROJECT)
    plan = compile_plan(
        result.snapshot,
        analysis=Transient(stop="10ms", step="10us", probes=["V(1)"]),
        traits=result.traits,
    )
    normalized = normalize(
        plan,
        RawResult("ngspice", "ngspice-43", "", 0, ""),
        assertions=[Assertion("max(V(1)) < 3.5 V", "pass")],
    )
    rendered = normalized.as_dict()

    assert rendered["plan"]["analysis"]["kind"] == "transient"
    assert rendered["backend_version"] == "ngspice-43"
    assert "models" in rendered and "assumptions" in rendered
    assert isinstance(rendered["coverage_gaps"], list)
    # And the pass is a finding, never a proof.
    assert "not proof of physical correctness" in rendered["finding"]["caveat"]
