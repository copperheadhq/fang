def test_at_r3_stable_ids_across_non_semantic_cad_formatting_changes():
    """AT-R3: reformatting a file changes no identifier."""
    from fang.kicad import read_netlist

    text = (EXAMPLES / "imported" / "reference.net").read_text()
    # A non-semantic reformat: different whitespace, different line breaks, and
    # a comment. None of it is meaning.
