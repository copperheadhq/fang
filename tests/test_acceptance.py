def test_at_k1_import_of_an_existing_project_with_every_mismatch_reported():
    """AT-K1: every mismatch against the source netlist is reported."""
    from fang.kicad import read_netlist
    from fang.netlist import compile_netlist
    from fang.sexpr import parse

    text = (EXAMPLES / "imported" / "reference.net").read_text()
    result = read_netlist(text, project_id=PROJECT, source="reference.net")
    snapshot = Snapshot(PROJECT, "REV-IMPORT", result.entities)
    recompiled = compile_netlist(snapshot)

    source = parse(text)
    source_refs = {
        comp.value("ref") for comp in source.child("components").children("comp")
    }
    recompiled_refs = {c.designator for c in recompiled.components}
    assert source_refs == recompiled_refs, "a component mismatch would appear here"

    source_nets = {
        net.pairs().get("name") for net in source.child("nets").children("net")
    }
    assert source_nets == {net.name for net in recompiled.nets}
    # Import fidelity is measured here, and what could not be modelled is named.
    assert result.report.recovered > 0
    assert isinstance(result.report.as_dict()["unrepresented"], list)


