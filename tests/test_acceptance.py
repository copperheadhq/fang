def test_at_r8_identical_derived_ids_across_machines_and_a_rename_reported_as_a_rename():
    """AT-R8: derivation is machine-independent, and a rename is a rename."""
    script = (
        "from fang.identity import derive;"
        "print(derive('PRJ-1','component','system.power.buck_3v3.U1').id)"
    )
    outputs = {
        subprocess.run(
            [sys.executable, "-c", script],
            capture_output=True,
            text=True,
            env={"PYTHONHASHSEED": seed, "PATH": "/usr/bin:/bin"},
            check=True,
        ).stdout.strip()
        for seed in ("0", "1", "99")
    }
    assert len(outputs) == 1
    assert outputs.pop() == derive("PRJ-1", "component", "system.power.buck_3v3.U1").id

    identity = derive(PROJECT, "component", "system.x.u1")
    before = {identity.id: Component(identity, provenance=tool_provenance())}
    after = {
        identity.id: Component(
            replace(identity, display_name="Renamed"), provenance=tool_provenance()
        )
    }
    changes = list(diff(before, after))
    assert [c.type for c in changes] == [ChangeClass.RENAME]
    assert ChangeClass.COMPONENT_ADDED not in {c.type for c in changes}
    assert ChangeClass.COMPONENT_REMOVED not in {c.type for c in changes}


