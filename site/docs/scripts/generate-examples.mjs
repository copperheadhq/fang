// Generates one documentation page per example, from the examples themselves:
//
//   src/content/docs/examples/<name>.md   the page
//   public/examples/<name>/*.svg          the views it renders
//
// Nothing here is written by hand, and that is the point. Every example folder
// already carries a README.md that explains what it is for and embeds its own
// renders, and `python examples/regenerate.py` already rewrites everything under
// out/ from the program beside it — which tests/test_examples.py then compares,
// so a committed output cannot drift from its program. Retyping any of that
// into a docs page would put a second copy of it in the repository, and the
// second copy is the one that goes stale. So the page is a projection: the
// README's prose, its links rewritten to resolve from the site, and the program
// and its outputs appended verbatim.
//
// Both generated trees are build output and are git-ignored. Regenerated by
// `npm run build` (see the prebuild script), so adding an example folder is all
// it takes for the example to appear in the docs.

import { readdir, readFile, writeFile, mkdir, rm, copyFile } from "node:fs/promises";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, "..", "..", "..");
const EXAMPLES = join(ROOT, "examples");
const CONTENT = join(here, "..", "src", "content", "docs", "examples");
const PUBLIC = join(here, "..", "public", "examples");
const REPO = "https://github.com/copperheadhq/fang";

// The three text projections every example writes, in the order a reader wants
// them: what it builds, whether it holds, and what the graph ended up with.
const OUTPUTS = [
  ["netlist.txt", "The parts, then the nets and the pads on them."],
  ["checks.txt", "Every check that ran, and every one left undecided."],
  ["graph.txt", "What the elaborated graph contains, by entity kind."],
];

async function exists(path) {
  try {
    await readdir(dirname(path));
    return (await readdir(dirname(path))).includes(basename(path));
  } catch {
    return false;
  }
}

// An example is a folder with a program named after it and an out/ beside it.
// That is the rule the test suite discovers them by, so it is the rule here:
// examples/imported/ and examples/parity/ have neither and say so themselves.
async function discover() {
  const found = [];
  for (const entry of await readdir(EXAMPLES, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name.startsWith("__")) continue;
    const dir = join(EXAMPLES, entry.name);
    const files = await readdir(dir);
    if (!files.includes(`${entry.name}.py`) || !files.includes("out")) continue;
    found.push({ name: entry.name, dir });
  }
  return found;
}

// "Smallest first", read off the graph rather than asserted in a list here: a
// hand-kept order would be one more thing to remember when an example is added.
function entityCount(graph) {
  const match = graph.match(/^\s*(\d+)\s+total$/m);
  return match ? Number(match[1]) : Number.MAX_SAFE_INTEGER;
}

// The first paragraph of prose, flattened to one line of plain text and cut at
// a sentence, which is what a description has to be: no markdown, no newlines.
//
// "Of prose" is the whole difficulty. A README may open with a code fence, a
// table, a quote or an image, and any of those read as a paragraph to a split
// on blank lines while making a nonsense description. They are skipped, and if
// an example has no prose at all its title stands in — a description that is
// merely thin is survivable, and failing the whole docs build over one README
// is not.
function describe(body, fallback) {
  const paragraph = body
    .split(/\n\s*\n/)
    .map((block) => block.trim())
    .find((block) => block && !/^([#>|]|```|!\[|<)/.test(block));
  if (!paragraph) return fallback;
  const flat = paragraph
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")   // links, keeping the text
    .replace(/[*_`]/g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (flat.length <= 160) return flat;
  const cut = flat.slice(0, 160);
  return `${cut.slice(0, Math.max(cut.lastIndexOf(". "), cut.lastIndexOf(" ")))}…`;
}

// A README's links are relative to its own folder, which is right in the
// repository and wrong on the site. Views resolve to the copies under public/;
// everything else — the program, the netlist, a sibling example — resolves to
// the file on GitHub, because that is where the thing actually is.
function resolveLinks(body, name) {
  return body.replace(/\]\(([^)]+)\)/g, (whole, target) => {
    if (/^(https?:|\/|#)/.test(target)) return whole;
    const view = target.match(/^out\/views\/(.+\.svg)$/);
    if (view) return `](/examples/${name}/${view[1]})`;
    const segments = [];
    for (const segment of `examples/${name}/${target}`.split("/")) {
      if (segment === "..") segments.pop();
      else if (segment !== ".") segments.push(segment);
    }
    return `](${REPO}/blob/main/${segments.join("/")})`;
  });
}

const examples = [];
for (const { name, dir } of await discover()) {
  const out = join(dir, "out");
  const readme = await readFile(join(dir, "README.md"), "utf8");
  const program = await readFile(join(dir, `${name}.py`), "utf8");
  const graph = await readFile(join(out, "graph.txt"), "utf8");

  // The H1 is the page title, which Starlight renders from the frontmatter, so
  // it is lifted out rather than left to be rendered a second time.
  const title = readme.match(/^#\s+(.+)$/m)?.[1].trim() ?? name;
  const body = readme.replace(/^#\s+.+$/m, "").trim();

  let views = [];
  try {
    views = (await readdir(join(out, "views"))).filter((f) => f.endsWith(".svg"));
  } catch {
    /* an example need not render a view */
  }

  examples.push({ name, dir, out, title, body, program, views, size: entityCount(graph) });
}

examples.sort((a, b) => a.size - b.size || a.name.localeCompare(b.name));

await rm(CONTENT, { recursive: true, force: true });
await rm(PUBLIC, { recursive: true, force: true });
await mkdir(CONTENT, { recursive: true });

for (const [index, example] of examples.entries()) {
  const { name, out, title, body, program, views } = example;

  if (views.length) {
    await mkdir(join(PUBLIC, name), { recursive: true });
    for (const view of views) {
      await copyFile(join(out, "views", view), join(PUBLIC, name, view));
    }
  }

  let page = `---
title: ${JSON.stringify(title)}
description: ${JSON.stringify(describe(body, title))}
sidebar:
  order: ${index + 1}
  label: ${JSON.stringify(name)}
  attrs:
    data-icon: puzzle
---

${resolveLinks(body, name)}

## The whole program

\`\`\`python title="examples/${name}/${name}.py"
${program.trim()}
\`\`\`

## The files it writes
`;

  for (const [file, blurb] of OUTPUTS) {
    let contents;
    try {
      contents = await readFile(join(out, file), "utf8");
    } catch {
      continue;
    }
    page += `\n${blurb}\n\n\`\`\`text title="out/${file}"\n${contents.trimEnd()}\n\`\`\`\n`;
  }

  page += `\nAll of it, including the KiCad netlist, is in
[\`examples/${name}/out/\`](${REPO}/tree/main/examples/${name}/out/). Rebuild it with:

\`\`\`bash
fang build examples/${name}/${name}.py
\`\`\`
`;

  await writeFile(join(CONTENT, `${name}.md`), page, "utf8");
}

console.log(
  `examples: ${examples.length} pages and ` +
    `${examples.reduce((n, e) => n + e.views.length, 0)} views written ` +
    `(${examples.map((e) => e.name).join(", ")})`
);
