// @ts-check
import { defineConfig } from "astro/config";
import starlight from "@astrojs/starlight";
import copperheadTheme from "@copperhead/starlight-theme";
import { existsSync, readFileSync } from "node:fs";
import rehypeTableLabels from "./src/plugins/rehype-table-labels.mjs";

const REPO = "https://github.com/copperheadhq/fang";

// The Examples section is written by scripts/generate-examples.mjs at
// prebuild, with each group named and ordered. Before that has run (a bare
// `astro dev`), fall back to listing the directory as it stands.
const EXAMPLES_SIDEBAR = new URL("./src/examples-sidebar.json", import.meta.url);
const exampleItems = existsSync(EXAMPLES_SIDEBAR)
  ? JSON.parse(readFileSync(EXAMPLES_SIDEBAR, "utf8"))
  : [{ autogenerate: { directory: "examples", collapsed: true } }];

// Nothing here is a visual decision. The identity — tokens, faces, the
// component overrides the stylesheet expects, and code-block styling — comes
// from the theme plugin. What is left is what belongs to fang: its name, its
// links, and its pages.
export default defineConfig({
  site: "https://fang.copperhead.sh",
  // Labels every table cell with its column's header, which the theme shows
  // when a narrow column turns each row into a card. A rehype plugin needs
  // @astrojs/markdown-remark installed; Astro 7 no longer ships it.
  markdown: { rehypePlugins: [rehypeTableLabels] },
  integrations: [
    starlight({
      title: "fang",
      description:
        "Hardware as Code. A Python-embedded language for circuit boards, and " +
        "a kernel that decides what is true about the design.",
      logo: { src: "./src/assets/mark.svg", alt: "" },
      favicon: "/brand/favicon.svg",
      social: [
        { icon: "external", label: "copperhead.sh", href: "https://copperhead.sh" },
        { icon: "github", label: "GitHub", href: REPO },
      ],
      editLink: { baseUrl: `${REPO}/edit/main/site/docs/` },
      customCss: ["./src/styles/examples.css"],
      lastUpdated: true,

      // The sidebar's release pill takes its repository from the github social
      // link above. No `version` is passed: fang's version has one source of
      // truth, `fang.__version__`, and a literal here would be a second.
      plugins: [copperheadTheme()],

      // The gtag is copperhead's own GA4 property, the same one copperhead.sh
      // carries: fang is a sub-brand, so its traffic belongs in that property
      // rather than in a second one. It sits here and not in the theme —
      // measurement is not identity, and a site consuming the theme should not
      // silently report into someone else's property.
      head: [
        { tag: "meta", attrs: { name: "theme-color", content: "#b87333" } },

        // Starlight gives every page og:title, og:description and
        // twitter:card from its own frontmatter, but no image — which
        // leaves `summary_large_image` declaring a card it never supplies,
        // so a shared docs link renders blank. One card for the whole site
        // rather than one per page: the page title is already the card's
        // headline wherever it is unfurled, and a per-page raster would be
        // a build step the docs site does not have.
        {
          tag: "meta",
          attrs: {
            property: "og:image",
            content: "https://fang.copperhead.sh/brand/og.png",
          },
        },
        { tag: "meta", attrs: { property: "og:image:type", content: "image/png" } },
        { tag: "meta", attrs: { property: "og:image:width", content: "1200" } },
        { tag: "meta", attrs: { property: "og:image:height", content: "630" } },
        {
          tag: "meta",
          attrs: {
            property: "og:image:alt",
            content:
              "fang: Hardware as Code, the line set under the copperhead / fang lockup, on fang's dark ground.",
          },
        },
        {
          tag: "meta",
          attrs: {
            name: "twitter:image",
            content: "https://fang.copperhead.sh/brand/og.png",
          },
        },
        {
          tag: "script",
          attrs: {
            async: true,
            src: "https://www.googletagmanager.com/gtag/js?id=G-KGEWCR918W",
          },
        },
        {
          tag: "script",
          content: [
            "window.dataLayer = window.dataLayer || [];",
            "function gtag() { dataLayer.push(arguments); }",
            "gtag('js', new Date());",
            "gtag('config', 'G-KGEWCR918W');",
          ].join("\n"),
        },
      ],

      // Autogenerated from the directory tree, so adding a page is still
      // adding a file. The leading icon each row carries is not named here:
      // copperhead's own sidebar sets it per link with
      // `attrs: { 'data-icon': ... }`, and Starlight merges the same attrs out
      // of a page's frontmatter, so each page names its own icon and this file
      // does not grow a line per page. Welcome is referenced by slug rather
      // than by link for that reason — only a slug entry reads frontmatter.
      sidebar: [
        {
          label: "Start here",
          items: [
            { slug: "index", label: "Welcome" },
            { autogenerate: { directory: "start" } },
          ],
        },
        { label: "Concepts", items: [{ autogenerate: { directory: "concepts" } }] },

        // Generated by scripts/generate-examples.mjs at prebuild, one page
        // per folder under examples/. Adding an example folder is all it
        // takes to add a page here. Closed until opened, groups inside it
        // too: the handbook alone is 73 pages, and an open list that long
        // pushes Reference off the screen. The group holding the page being
        // read still opens.
        { label: "Examples", collapsed: true, items: exampleItems },
        { label: "Reference", items: [{ autogenerate: { directory: "reference" } }] },
      ],
    }),
  ],
});
